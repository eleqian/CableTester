/* 12x24字体信息 */
const font_info_t Font12x24_Info = {
    .width = 12,
    .height = 24,
    .first_char = 0x20,
    .char_count = 96,
    .data = (const uint8_t *)Font12x24_Data};

/**
 * @brief  获取字体信息
 * @param  type: 字体类型
 * @return 字体信息指针
 */
const font_info_t *Font_GetInfo(font_type_t type)
{
    switch (type) {
    case FONT_5x8:
        return &Font5x8_Info;
    case FONT_8x16:
        return &Font8x16_Info;
    case FONT_12x24:
        return &Font12x24_Info;
    default:
        return &Font5x8_Info;  // 默认返回5x8字体
    }
}

/**
 * @brief  获取字符宽度
 * @param  type: 字体类型
 * @return 字符宽度（像素）
 */
uint8_t Font_GetCharWidth(font_type_t type)
{
    const font_info_t *font = Font_GetInfo(type);
    return font->width;
}

/**
 * @brief  获取字符高度
 * @param  type: 字体类型
 * @return 字符高度（像素）
 */
uint8_t Font_GetCharHeight(font_type_t type)
{
    const font_info_t *font = Font_GetInfo(type);
    return font->height;
}

/**
 * @brief  获取字符字体数据
 * @param  type: 字体类型
 * @param  ch: 字符
 * @return 字符字体数据
 */
const uint8_t *Font_GetCharData(font_type_t type, int ch)
{
    const font_info_t *font_info = Font_GetInfo(type);

    // 检查字符范围
    if ((uint8_t)ch < font_info->first_char || (uint8_t)ch >= (font_info->first_char + font_info->char_count)) {
        return (void *)0;
    }

    // 计算字体索引
    uint8_t font_index = (uint8_t)ch - font_info->first_char;
    const uint8_t *font_data = font_info->data + font_index * font_info->width * ((font_info->height + 7) / 8);

    return font_data;
}
